// HUD check on phone viewports: screenshots of the awake and idle states, the menu, the stratagem drawer, the tray and draw mode in a busy moment.
// Usage: node test/hud.mjs [portrait|landscape|small] 
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VP = { portrait: { width: 390, height: 844 }, landscape: { width: 844, height: 390 }, small: { width: 360, height: 640 } };
const vp = process.argv[2] || 'portrait';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: VP[vp], hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text()); });
const out = (n) => path.join(root, 'test/shots', `hud-${vp}-${n}.png`);
const tap = async (sel) => { const b = await page.locator(sel).first().boundingBox(); if (!b) throw new Error('no box ' + sel); await page.touchscreen.tap(b.x + b.width / 2, b.y + b.height / 2); };
await page.goto('file://' + path.join(root, 'dist/orbital-fire-support.html') + '?seed=31&faction=bugs&biome=grass&fast=1');
await page.waitForTimeout(500);
await tap('#btn-play'); await page.waitForTimeout(300);
if (await page.isVisible('#btn-notice')) await tap('#btn-notice');
await page.waitForTimeout(300);
await tap('#shop-go'); await page.waitForTimeout(500);
await page.waitForFunction(() => !document.getElementById('b-continue').disabled, null, { timeout: 15000 });
await tap('#b-continue'); await page.waitForTimeout(1500);
await page.screenshot({ path: out('1-start') });
await page.waitForTimeout(9000);
await page.evaluate(() => { const m = window.__game.mission; m.callSeaf(m.hx + 28, m.hy + 22); });
await page.waitForTimeout(9000);
await page.evaluate(() => { const m = window.__game.mission; m.splitSeaf(); m.assault.nextAt = m.t + 0.5; });
await page.waitForTimeout(3500);
await page.screenshot({ path: out('2-busy-awake') });
await page.waitForTimeout(3600);
await page.screenshot({ path: out('3-busy-idle') });
await tap('#btn-menu'); await page.waitForTimeout(300);
await page.screenshot({ path: out('4-menu') });
await tap('.mn[data-mn=strats]'); await page.waitForTimeout(300);
await page.screenshot({ path: out('5-strats') });
await page.waitForTimeout(8300);
await tap('#dk-sq'); await page.waitForTimeout(300);
await page.screenshot({ path: out('6-tray') });
await tap('#squads .sqa[data-a=draw]'); await page.waitForTimeout(300);
const W = VP[vp].width, H = VP[vp].height;
const cdp = await ctx.newCDPSession(page);
const pts = []; for (let k = 0; k <= 14; k++) pts.push({ x: W / 2 - 60 + k * 9, y: H * 0.45 + Math.sin(k / 2.6) * 24 });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [pts[0]] });
for (const p of pts.slice(1)) { await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [p] }); await page.waitForTimeout(25); }
await page.screenshot({ path: out('7-drawing') });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'no page errors');
await browser.close();
process.exit(errs.length ? 1 : 0);
